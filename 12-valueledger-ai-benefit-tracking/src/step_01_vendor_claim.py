"""
Step 1 - Before: the vendor-style benefit claim.

A copilot business case multiplies the number of times the tool was used by an
assumed number of minutes saved per use. It needs only a usage log and one
assumption, so it is the number that reaches leadership first.

  claimed hours = usage events x assumed minutes saved per use / 60

The assumption is printed below. It comes from data/copilots.csv, where both
copilots carry the same 12 minutes per use. Nothing in this calculation looks
at the people who did not use the tool, at the weeks before launch, at rework,
at a second tool logging the same task, or at a budget line.

All data is synthetic and generated by data/_generate.py.

Run (from src/):
    python3 step_01_vendor_claim.py
"""

from __future__ import annotations

import csv
import json

from valueledger_core import (
    POST_WEEKS, ensure_out, fmt_int, fmt_usd, load_data, build_agg,
    scenario_by_key, total, value_by_cc,
)


def claim(ds, agg, post_weeks: list) -> dict:
    """Usage events times the assumed minutes per use, for the treated cohort."""
    assumed_a = ds.copilots["A"]["assumed_minutes_saved_per_use"]
    assumed_b = ds.copilots["B"]["assumed_minutes_saved_per_use"]
    ea = total(agg, agg.treated, "EA", post_weeks)
    eb = total(agg, agg.treated, "EB", post_weeks)
    eboth = total(agg, agg.treated, "EBOTH", post_weeks)
    hours_by_cc = {}
    for t in agg.treated:
        cc = agg.teams[t]["cc"]
        mins = (total(agg, [t], "EA", post_weeks) * assumed_a
                + total(agg, [t], "EB", post_weeks) * assumed_b)
        hours_by_cc[cc] = hours_by_cc.get(cc, 0.0) + mins / 60.0
    hours = (ea * assumed_a + eb * assumed_b) / 60.0
    n = agg.n_treated_people
    return {
        "assumed_min_a": assumed_a,
        "assumed_min_b": assumed_b,
        "events_a": ea,
        "events_b": eb,
        "events_both": eboth,
        "events_logged": ea + eb,
        "events_distinct": ea + eb - eboth,
        "claimed_hours": hours,
        "claimed_hours_by_cc": hours_by_cc,
        "claimed_value_usd": value_by_cc(ds, hours_by_cc),
        "n_treated": n,
        "hours_per_person": hours / n if n else 0.0,
    }


def main() -> None:
    ds = load_data()
    agg = build_agg(ds, scenario_by_key("all"))
    c = claim(ds, agg, POST_WEEKS)
    n_teams = len(agg.treated)

    print("STEP 1 - Before: the vendor-style benefit claim")
    print("Synthetic data. %d people, 26 weeks; %d people in %d treated teams got a copilot in week 13."
          % (len(ds.employees), c["n_treated"], n_teams))
    print()
    print("Business-case assumption (data/copilots.csv)")
    for cid in ("A", "B"):
        cp = ds.copilots[cid]
        print("  copilot %s, %-26s %s  assumed minutes saved per use: %s"
              % (cid, cp["copilot_name"] + ",", cp["use_case_id"], fmt_int(cp["assumed_minutes_saved_per_use"])))
    print()
    print("Usage log, the 14 weeks after launch")
    print("  copilot A events:                     %s" % fmt_int(c["events_a"]))
    print("  copilot B events:                     %s" % fmt_int(c["events_b"]))
    print("  events logged, both tools added up:   %s" % fmt_int(c["events_logged"]))
    print()
    print("Claim")
    print("  claimed hours  = events x assumed minutes / 60 = %s h" % fmt_int(c["claimed_hours"]))
    print("  per treated person                             = %.1f h in 14 weeks" % c["hours_per_person"])
    print("  implied value at loaded cost rates             = %s" % fmt_usd(c["claimed_value_usd"]))
    print()
    print("What this number never asked: saved against what? net of what corrections?")
    print("counted once or twice? and in which budget line can finance find it?")

    out = ensure_out()
    with open(out / "step_01_claim.json", "w") as f:
        json.dump(c, f, indent=2, sort_keys=True)
        f.write("\n")
    with open(out / "step_01_claim_by_cost_center.csv", "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["cost_center_id", "claimed_hours", "loaded_cost_per_hour_usd", "claimed_value_usd"])
        for cc in sorted(c["claimed_hours_by_cc"]):
            h = c["claimed_hours_by_cc"][cc]
            r = ds.budget[cc]["loaded_cost_per_hour_usd"]
            w.writerow([cc, "%.1f" % h, "%.2f" % r, "%.0f" % (h * r)])


if __name__ == "__main__":
    main()
