def pct(x: float, base: float) -> str:
    return "%+.0f%%" % (100.0 * x / base) if base else "n/a"


def over_word(err: float) -> str:
    """OVERSTATED or UNDERSTATED, from the sign of the error against the answer key."""
    return "OVERSTATED" if err > 0 else "UNDERSTATED"


def over_phrase(err: float) -> str:
    return "over the truth" if err > 0 else "under the truth"


