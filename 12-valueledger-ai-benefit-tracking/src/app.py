FOCUS_NOTES = {
    "claim": (
        "Usage events times an assumed 12 minutes per use. It needs only a usage log. It does not look at people who "
        "did not use the tool, at the weeks before launch, at rework, or at a second tool logging the same task."
    ),
    "prepost": (
        "Minutes per task before and after, treated people only. It measures the work, not the log, so it beats the "
        "claim. It has no counterfactual: the seasonal workload easing and the head start the enthusiastic teams "
        "already had are credited to the copilot, and rework is not subtracted."
    ),
    "ledger": (
        "Difference-in-differences against the holdout, net of rework, with decay, deduplication, a budget-line split "
        "and team-level bootstrap intervals. It still cannot see a change the enthusiastic teams made on their own "
        "after launch. That residual bias is printed in step 4."
    ),
}


def pct(x: float, base: float) -> str:
    return "%+.0f%%" % (100.0 * x / base) if base else "n/a"


