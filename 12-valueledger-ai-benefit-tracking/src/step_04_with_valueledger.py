# One scenario, everything
# ---------------------------------------------------------------------------
def run_scenario(key: str, reps: int = BOOT_REPS) -> dict:
    ds = load_data()
    spec = scenario_by_key(key)
    agg = build_agg(ds, spec)
    post = spec["post"]
    pre = PRE_WEEKS
    n = agg.n_treated_people
    months = len(post) / WEEKS_PER_MONTH

    c = core_arrays(agg, agg.treated, agg.holdout)
    est = estimate(ds, c, pre, post)
    cl = claim(ds, agg, post)
    pp = prepost(ds, agg, pre, post)
    tr = truth_summary(ds, agg, post)
    ci = bootstrap(ds, agg, pre, post, reps=reps)
    pp_ci = prepost_interval(ds, agg, pre, post, reps=reps)

    # per-copilot attribution (policy: shared tasks split equally)
    a_only = cl["events_a"] - cl["events_both"]
    b_only = cl["events_b"] - cl["events_both"]
    shared = cl["events_both"]
    distinct = a_only + b_only + shared
    cop = []
    seats = {"A": agg.people_by_tools.get("A", 0) + agg.people_by_tools.get("AB", 0),
             "B": agg.people_by_tools.get("B", 0) + agg.people_by_tools.get("AB", 0)}
    for cid, mine_only, logged in (("A", a_only, cl["events_a"]), ("B", b_only, cl["events_b"])):
        share = (mine_only + shared / 2.0) / distinct if distinct else 0.0
        cp = ds.copilots[cid]
        cop.append({
            "copilot_id": cid,
            "copilot_name": cp["copilot_name"],
            "use_case_id": cp["use_case_id"],
            "approval_status": cp["approval_status"],
            "booked": cp["approval_status"] == "approved",
            "seats": seats[cid],
            "claimed_hours": logged * cp["assumed_minutes_saved_per_use"] / 60.0,
            "ledger_share": share,
            "ledger_net_hours": est["net_hours"] * share,
            "cost_usd": seats[cid] * cp["seat_cost_usd_per_month"] * months,
        })
    cost_total = sum(x["cost_usd"] for x in cop)

    rate = blended_rate(ds, agg, post)
    errs = {
        "claim_hours_error": cl["claimed_hours"] - tr["net_hours"],
        "prepost_hours_error": pp["hours"] - tr["net_hours"],
        "ledger_hours_error": est["net_hours"] - tr["net_hours"],
    }
    covers = {}
    if "net_hours" in ci:
        covers["ledger"] = ci["net_hours"][0] <= tr["net_hours"] <= ci["net_hours"][1]
    covers["prepost"] = pp_ci[0] <= tr["net_hours"] <= pp_ci[1]

    # guardrail by cost center (computed inside the ledger rule): rework share of gross time saved
    guard = [{"cost_center_id": r["cost_center_id"], "gross_hours": r["gross_hours"],
              "rework_hours": r["rework_hours"], "rework_share": r["rework_share"], "hold": r["hold"]}
             for r in est["cc_rows"]]

    # utility: overstatement per treated person, scaled to a modeled bank headcount
    claim_gap_pp = (cl["claimed_hours"] - tr["net_hours"]) / n
    ledger_gap_pp = (est["net_hours"] - tr["net_hours"]) / n
    removed_pp = claim_gap_pp - abs(ledger_gap_pp)
    hidden_pp = tr["hidden_drift_hours"] / n
    utility = {
        "hidden_bias_hours_per_person": hidden_pp,
        "phantom_removed_if_full_bias_hours_per_person": claim_gap_pp - hidden_pp,
        "n_treated": n,
        "claim_gap_hours_per_person": claim_gap_pp,
        "ledger_gap_hours_per_person": ledger_gap_pp,
        "phantom_removed_hours_per_person": removed_pp,
        "bank_headcount_assumed": BANK_ELIGIBLE_HEADCOUNT,
        "scaled_hours": round_sig(removed_pp * BANK_ELIGIBLE_HEADCOUNT, 3),
        "scaled_value_usd": round_sig(removed_pp * BANK_ELIGIBLE_HEADCOUNT * rate, 3),
        "blended_rate_usd": rate,
    }

    return {
        "key": key,
        "label": spec["label"],
        "focus": spec["focus"],
        "post_weeks": post,
        "n_treated": n,
        "n_holdout": agg.n_holdout_people,
        "n_treated_teams": len(agg.treated),
        "n_holdout_teams": len(agg.holdout),
        "claim": cl,
        "prepost": pp,
        "prepost_ci": list(pp_ci),
        "ledger": est,
        "ledger_ci": {k: list(v) for k, v in ci.items()},
        "truth": tr,
        "errors": errs,
        "ci_covers_truth": covers,
        "copilots": cop,
        "cost_usd": cost_total,
        "guardrail": guard,
        "utility": utility,
        "blended_rate_usd": rate,
    }


