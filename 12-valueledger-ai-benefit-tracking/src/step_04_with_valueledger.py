"""
Step 4 - The fix: ValueLedger.

Six moves, each answering one deficiency from Step 3:

  1. Holdout cohort and difference-in-differences. The effect is the change in
     minutes per task for treated teams MINUS the change for the holdout teams
     over the same weeks. The seasonal workload trend hits both groups, so it
     cancels. A pre-period check (gap slope and a placebo launch) says whether
     the holdout is a fair stand-in, and prints how it did.
  2. Net of rework. Minutes spent correcting copilot output are subtracted.
  3. A weekly effect curve with decay. Effect per distinct assisted task by week,
     with an exponential fit, so the launch month is not annualised.
  4. Overlap deduplication. Tasks are counted once. Shared tasks are split
     equally between the two copilots (a policy choice, printed).
  5. A hard-versus-soft ledger tied to the budget table. Freed time only counts
     as cash where the cost center has a cash lever, and only up to the
     addressable spend on that line. The rest is capacity.
  6. Seeded cluster bootstrap confidence intervals, resampling whole teams
     within each arm (standard library, 1,000 resamples).

One known limit is left in on purpose: selection on things the data cannot see.
The enthusiastic teams made a process change after launch that is not in any
column. The pre-period check cannot see it. The residual bias is printed.

Quality guardrail (interlock with 04 EvalForge): a cost center whose rework
eats more than 40% of its gross time saved is held, because speed is being
bought with errors. Here rework minutes stand in for an EvalForge pass rate.

Use-case approval (interlock with 11 TierGate) and cost (interlock with 07
InferenceLens) are read from data/copilots.csv, a synthetic table. The links
to those projects are design, not built here.

All data is synthetic and generated by data/_generate.py.

Run (from src/):
    python3 step_04_with_valueledger.py
"""

