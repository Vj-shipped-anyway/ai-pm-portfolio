# One pass over the teams -> every array the estimators need
# ---------------------------------------------------------------------------
def core_arrays(agg, teams_t: list, teams_h: list) -> dict:
    n = N_WEEKS
    c = {k: [0.0] * n for k in ("Tt", "Mt", "Th", "Mh", "EA", "EB", "EBOTH", "R")}
    cc_a = {}
    cc_r = {}
    for t in teams_t:
        rec = agg.teams[t]
        for key, name in (("T", "Tt"), ("M", "Mt"), ("EA", "EA"), ("EB", "EB"),
                          ("EBOTH", "EBOTH"), ("R", "R")):
            arr = rec[key]
            dst = c[name]
            for i in range(n):
                dst[i] += arr[i]
        cc = rec["cc"]
        if cc not in cc_a:
            cc_a[cc] = [0.0] * n
            cc_r[cc] = [0.0] * n
        for i in range(n):
            cc_a[cc][i] += rec["EA"][i] + rec["EB"][i] - rec["EBOTH"][i]
            cc_r[cc][i] += rec["R"][i]
    for t in teams_h:
        rec = agg.teams[t]
        for key, name in (("T", "Th"), ("M", "Mh")):
            arr = rec[key]
            dst = c[name]
            for i in range(n):
                dst[i] += arr[i]
    c["cc_a"] = cc_a
    c["cc_r"] = cc_r
    return c


def estimate(ds, c: dict, pre: list, post: list) -> dict:
    """Every ValueLedger number from one set of arrays (the real data or a resample)."""
    pi = [w - 1 for w in pre]
    qi = [w - 1 for w in post]
    pre_t = sum(c["Mt"][i] for i in pi) / sum(c["Tt"][i] for i in pi)
    pre_h = sum(c["Mh"][i] for i in pi) / sum(c["Th"][i] for i in pi)

    gross_w, rework_w, assisted_w, did_w, pp_w, tasks_w = [], [], [], [], [], []
    for i in qi:
        m_t = c["Mt"][i] / c["Tt"][i]
        m_h = c["Mh"][i] / c["Th"][i]
        did = (pre_t - m_t) - (pre_h - m_h)
        did_w.append(did)
        pp_w.append(pre_t - m_t)
        tasks_w.append(c["Tt"][i])
        gross_w.append(did * c["Tt"][i])
        rework_w.append(c["R"][i])
        assisted_w.append(c["EA"][i] + c["EB"][i] - c["EBOTH"][i])
    gross_min = sum(gross_w)
    rework_min = sum(rework_w)
    net_min = gross_min - rework_min
    prepost_min = sum(p * t for p, t in zip(pp_w, tasks_w))

    # allocate gross to cost centers by deduplicated assisted tasks; rework stays where it was logged
    gross_cc, rework_cc = {}, {}
    for cc, arr in c["cc_a"].items():
        g = 0.0
        for k, i in enumerate(qi):
            if assisted_w[k] > 0:
                g += gross_w[k] * arr[i] / assisted_w[k]
        gross_cc[cc] = g / 60.0
        rework_cc[cc] = sum(c["cc_r"][cc][i] for i in qi) / 60.0
    hs = apply_ledger_rule(ds, gross_cc, rework_cc, len(post))

    # pre-period trend check on the treated-minus-holdout gap, weeks 1-12
    gaps = [c["Mt"][i] / c["Tt"][i] - c["Mh"][i] / c["Th"][i] for i in pi]
    slope = ols_slope([float(w) for w in pre], gaps)
    # placebo: pretend launch happened in week 7, using only weeks 1-12
    half = len(pre) // 2
    a_idx, b_idx = pi[:half], pi[half:]
    def pooled(m, t, idx):
        return sum(m[i] for i in idx) / sum(t[i] for i in idx)
    placebo = ((pooled(c["Mt"], c["Tt"], a_idx) - pooled(c["Mt"], c["Tt"], b_idx))
               - (pooled(c["Mh"], c["Th"], a_idx) - pooled(c["Mh"], c["Th"], b_idx)))

    ys_raw = [g / a if a > 0 else 0.0 for g, a in zip(gross_w, assisted_w)]
    out = {
        "pre_mean_treated": pre_t,
        "pre_mean_holdout": pre_h,
        "baseline_gap_min": pre_t - pre_h,
        "gross_did_min": gross_min,
        "gross_did_hours": gross_min / 60.0,
        "rework_hours": rework_min / 60.0,
        "net_hours": net_min / 60.0,
        "prepost_hours": prepost_min / 60.0,
        "hard_usd": hs["hard_usd"],
        "soft_usd": hs["soft_usd"],
        "value_usd": hs["value_usd"],
        "cc_rows": hs["rows"],
        "trend_gap_slope": slope,
        "placebo_effect": placebo,
        "assisted_tasks": sum(assisted_w),
        "events_logged": sum(c["EA"][i] + c["EB"][i] for i in qi),
        "weekly": {
            "weeks": list(post),
            "did_per_task": did_w,
            "prepost_per_task": pp_w,
            "tasks": tasks_w,
            "gross_min": gross_w,
            "rework_min": rework_w,
            "assisted": assisted_w,
            "gross_per_assisted": ys_raw,
        },
    }

    # weekly effect curve with decay, per distinct assisted task (full window only)
    if len(post) == len(POST_WEEKS):
        ts = [float(w - LAUNCH_WEEK) for w in post]
        ys = ys_raw
        a_fit, b_fit, k_fit = fit_decay(ts, ys, assisted_w)
        fitted = [a_fit + b_fit * math.exp(-k_fit * t) for t in ts]
        net_fit_min = [f * a - r for f, a, r in zip(fitted, assisted_w, rework_w)]
        early = sum(net_fit_min[:4]) / 4.0 / 60.0
        steady = sum(net_fit_min[-4:]) / 4.0 / 60.0
        out["curve"] = {
            "steady_min_per_use": a_fit,
            "launch_bonus_min_per_use": b_fit,
            "decay_k": k_fit,
            "half_life_weeks": (math.log(2.0) / k_fit) if k_fit > 0 else float("inf"),
            "raw_gross_per_assisted": ys,
            "fitted_gross_per_assisted": fitted,
            "raw_rework_per_assisted": [r / a if a > 0 else 0.0 for r, a in zip(rework_w, assisted_w)],
            "early_weekly_net_hours": early,
            "steady_weekly_net_hours": steady,
            "early_over_steady": early / steady if steady > 0 else float("nan"),
        }
    return out


