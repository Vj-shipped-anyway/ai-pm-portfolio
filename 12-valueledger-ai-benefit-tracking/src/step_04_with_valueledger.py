# Bootstrap: resample whole teams within each arm
# ---------------------------------------------------------------------------
def bootstrap(ds, agg, pre: list, post: list, reps: int = BOOT_REPS, seed: int = BOOT_SEED) -> dict:
    rng = random.Random(seed)
    nt, nh = len(agg.treated), len(agg.holdout)
    keys = ("net_hours", "gross_did_hours", "prepost_hours", "hard_usd", "soft_usd", "value_usd",
            "trend_gap_slope", "placebo_effect")
    curve_keys = ("steady_min_per_use", "decay_k", "half_life_weeks", "early_weekly_net_hours",
                  "steady_weekly_net_hours", "early_over_steady")
    draws = {k: [] for k in keys + curve_keys}
    for _ in range(reps):
        tt = [agg.treated[rng.randrange(nt)] for _ in range(nt)]
        th = [agg.holdout[rng.randrange(nh)] for _ in range(nh)]
        e = estimate(ds, core_arrays(agg, tt, th), pre, post)
        for k in keys:
            draws[k].append(e[k])
        if "curve" in e:
            for k in curve_keys:
                v = e["curve"][k]
                if v == v and v != float("inf"):
                    draws[k].append(v)
    out = {}
    for k, v in draws.items():
        if v:
            lo, hi = interval(v)
            out[k] = (lo, hi)
    # pre/post resamples the treated teams only; it has no holdout
    return out


def prepost_interval(ds, agg, pre: list, post: list, reps: int = BOOT_REPS, seed: int = BOOT_SEED) -> tuple:
    rng = random.Random(seed + 1)
    nt = len(agg.treated)
    vals = []
    for _ in range(reps):
        tt = [agg.treated[rng.randrange(nt)] for _ in range(nt)]
        vals.append(prepost(ds, agg, pre, post, teams=tt)["hours"])
    return interval(vals)


