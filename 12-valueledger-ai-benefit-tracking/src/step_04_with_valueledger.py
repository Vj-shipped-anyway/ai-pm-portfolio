# Answer key
# ---------------------------------------------------------------------------
def truth_summary(ds, agg, post: list) -> dict:
    tt = agg.treated
    g = total(agg, tt, "G", post)
    rw = total(agg, tt, "RW", post)
    hid = total(agg, tt, "HID", post)
    ass = total(agg, tt, "AS", post)
    gross_cc, rework_cc = {}, {}
    for t in tt:
        cc = agg.teams[t]["cc"]
        gross_cc[cc] = gross_cc.get(cc, 0.0) + total(agg, [t], "G", post) / 60.0
        rework_cc[cc] = rework_cc.get(cc, 0.0) + total(agg, [t], "RW", post) / 60.0
    hs = apply_ledger_rule(ds, gross_cc, rework_cc, len(post))
    p = ds.params
    out = {
        "gross_hours": g / 60.0,
        "rework_hours": rw / 60.0,
        "net_hours": (g - rw) / 60.0,
        "hidden_drift_hours": hid / 60.0,
        "assisted_tasks": ass,
        "hard_usd": hs["hard_usd"],
        "soft_usd": hs["soft_usd"],
        "value_usd": hs["value_usd"],
        "cc_rows": hs["rows"],
    }
    if len(post) == len(POST_WEEKS):
        # asymptote = injected steady-state minutes x the assisted-weighted skill of the treated people
        denom = 0.0
        for w in post:
            t = w - LAUNCH_WEEK
            gt = p["steady_min_per_assisted_task"] + p["novelty_min_per_assisted_task"] * math.exp(
                -p["novelty_decay_k_per_week"] * t)
            denom += total(agg, tt, "AS", [w]) * gt
        skill = g / denom if denom else 1.0
        wk_net = [(total(agg, tt, "G", [w]) - total(agg, tt, "RW", [w])) / 60.0 for w in post]
        out["steady_min_per_use"] = p["steady_min_per_assisted_task"] * skill
        out["decay_k"] = p["novelty_decay_k_per_week"]
        out["half_life_weeks"] = p["novelty_half_life_weeks"]
        out["early_weekly_net_hours"] = sum(wk_net[:4]) / 4.0
        out["steady_weekly_net_hours"] = sum(wk_net[-4:]) / 4.0
        out["early_over_steady"] = out["early_weekly_net_hours"] / out["steady_weekly_net_hours"]
    out["weekly_gross_per_assisted"] = [
        total(agg, tt, "G", [w]) / total(agg, tt, "AS", [w]) for w in post]
    out["weekly_net_per_assisted"] = [
        (total(agg, tt, "G", [w]) - total(agg, tt, "RW", [w])) / total(agg, tt, "AS", [w]) for w in post]
    out["weekly_net_hours"] = [
        (total(agg, tt, "G", [w]) - total(agg, tt, "RW", [w])) / 60.0 for w in post]
    return out


