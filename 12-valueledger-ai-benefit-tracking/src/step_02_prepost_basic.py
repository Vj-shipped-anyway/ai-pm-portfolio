"""
Step 2 - The basic approach: a pre/post comparison of the treated cohort only.

The next thing a careful analyst tries after doubting the vendor claim is to
stop trusting usage and look at the work itself: minutes per task before the
copilot against minutes per task after it, for the people who got the tool.

  effect per task   = mean minutes per task, weeks 1-12  -  weekly minutes per task, weeks 13-26
  hours saved       = sum over post weeks of (effect per task x tasks completed that week) / 60

This is a real measurement of the work, not a usage count, so it is better than
Step 1. It still has no counterfactual: it credits the copilot with everything
that changed between the two periods. It also ignores the rework the copilot's
output caused, because rework minutes sit in a separate column.

All data is synthetic and generated by data/_generate.py.

Run (from src/):
    python3 step_02_prepost_basic.py
"""

from __future__ import annotations

import csv
import json

from valueledger_core import (
    POST_WEEKS, PRE_WEEKS, ensure_out, fmt_int, fmt_usd, load_data, build_agg,
    scenario_by_key, total, value_by_cc,
)
from step_01_vendor_claim import claim


def prepost(ds, agg, pre_weeks: list, post_weeks: list, teams: list = None) -> dict:
    """Pre/post on the treated cohort (or a resample of its teams).

    Returns the pooled pre mean, the weekly post means, the weekly effect per
    task, the hours saved, and the hours allocated to cost centers by task share
    (a pre/post analyst has tasks, not assisted tasks).
    """
    teams = agg.treated if teams is None else teams
    pre_t = total(agg, teams, "T", pre_weeks)
    pre_m = total(agg, teams, "M", pre_weeks)
    pre_mean = pre_m / pre_t
    weekly_effect = []
    minutes = 0.0
    for w in post_weeks:
        t_w = total(agg, teams, "T", [w])
        m_w = total(agg, teams, "M", [w])
        mean_w = m_w / t_w
        weekly_effect.append(pre_mean - mean_w)
        minutes += (pre_mean - mean_w) * t_w
    post_tasks = total(agg, teams, "T", post_weeks)
    post_mean = total(agg, teams, "M", post_weeks) / post_tasks
    hours = minutes / 60.0
    # allocate to cost centers by task share
    by_cc = {}
    for t in set(teams):
        cc = agg.teams[t]["cc"]
        by_cc[cc] = by_cc.get(cc, 0.0) + teams.count(t) * total(agg, [t], "T", post_weeks)
    share_total = sum(by_cc.values())
    hours_by_cc = {cc: hours * v / share_total for cc, v in by_cc.items()}
    return {
        "pre_mean_min_per_task": pre_mean,
        "post_mean_min_per_task": post_mean,
        "effect_per_task_min": pre_mean - post_mean,
        "weekly_effect_per_task_min": weekly_effect,
        "post_tasks": post_tasks,
        "hours": hours,
        "hours_by_cc": hours_by_cc,
        "value_usd": value_by_cc(ds, hours_by_cc),
    }


def main() -> None:
    ds = load_data()
    agg = build_agg(ds, scenario_by_key("all"))
    p = prepost(ds, agg, PRE_WEEKS, POST_WEEKS)
    c = claim(ds, agg, POST_WEEKS)
    n = agg.n_treated_people

    print("STEP 2 - The basic approach: pre/post on the treated cohort only")
    print("Treated cohort: %d people. Pre = weeks 1-12, post = weeks 13-26." % n)
    print()
    print("  mean minutes per task, pre:         %.2f" % p["pre_mean_min_per_task"])
    print("  mean minutes per task, post:        %.2f" % p["post_mean_min_per_task"])
    print("  reduction per task:                 %.2f min" % p["effect_per_task_min"])
    print("  tasks completed in the post weeks:  %s" % fmt_int(p["post_tasks"]))
    print()
    print("  estimated hours saved:              %s h  (%.1f h per treated person)" % (fmt_int(p["hours"]), p["hours"] / n))
    print("  implied value at loaded cost rates: %s" % fmt_usd(p["value_usd"]))
    print()
    print("Against Step 1: the claim said %s h; this says %s h (%.0f%% of the claim)."
          % (fmt_int(c["claimed_hours"]), fmt_int(p["hours"]), 100.0 * p["hours"] / c["claimed_hours"]))
    print("It looks like a measurement because it uses the work, not the usage log.")
    print("It is still a before-and-after: whatever else changed in the 26 weeks is credited to the copilot.")
    print()
    print("Weekly reduction per task, min (week 13 ... 26):")
    print("  " + "  ".join("%.1f" % x for x in p["weekly_effect_per_task_min"]))

    out = ensure_out()
    with open(out / "step_02_prepost.json", "w") as f:
        json.dump(p, f, indent=2, sort_keys=True)
        f.write("\n")
    with open(out / "step_02_prepost_weekly.csv", "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["week", "prepost_effect_per_task_min"])
        for wk, e in zip(POST_WEEKS, p["weekly_effect_per_task_min"]):
            w.writerow([wk, "%.3f" % e])


if __name__ == "__main__":
    main()
